// Run using the google-browser-mock.js init script and a disposable test profile.
(async () => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const click = selector => { const el = document.querySelector(selector); if (!el) throw Error(`Missing ${selector}`); el.click(); };
  const fill = (name, value) => { const input = document.querySelector(`#editor [name="${name}"]`); input.value = value; input.dispatchEvent(new Event('change', { bubbles: true })); };
  const submit = () => document.querySelector('#editor form').requestSubmit();
  const read = () => JSON.parse(localStorage.getItem('daylight-planner-v1'));
  const waitFor = async check => { for (let i = 0; i < 100; i++) { if (check()) return; await new Promise(resolve => setTimeout(resolve, 30)); } throw Error('Timed out waiting for UI'); };
  window.__plannerBeforeGoogleTest = localStorage.getItem('daylight-planner-v1');
  const results = [];
  click('.layout-shortcut'); fill('defaultView', 'week'); fill('weekStartsOn', '0'); fill('density', 'compact');
  click('[name="accent"][value="forest"]'); click('[name="showStats"]'); click('[name="showTasks"]'); submit();
  assert(document.documentElement.dataset.accent === 'forest', 'Accent did not apply');
  assert(getComputedStyle(document.querySelector('.stats')).display === 'none', 'Stats are visible');
  assert(getComputedStyle(document.querySelector('.right-panel')).display === 'none', 'Task panel is visible');
  assert(document.querySelector('.day-header small').textContent === 'Sun', 'Week did not start on Sunday');
  assert(document.querySelector('.time-slot').getBoundingClientRect().height === 26, 'Compact grid spacing failed');
  assert(read().layout.density === 'compact', 'Layout not persisted'); results.push('Layout controls apply and persist');
  click('.layout-shortcut'); click('[data-tab="connections"]');
  assert(document.querySelector('[data-action="google-connect"]').disabled, 'Unconfigured connection should be disabled');
  click('.connection-setup summary'); fill('clientId', '123-fixture.apps.googleusercontent.com'); submit();
  click('[data-action="google-connect"]');
  await waitFor(() => document.querySelector('[data-source="calendar"]') && document.querySelector('[data-source="classroom"]'));
  assert(window.__googleFixture.signIns === 1, 'Both services should share one sign-in');
  assert(window.__googleFixture.scopes.includes('calendar.events.readonly') && window.__googleFixture.scopes.includes('classroom.coursework.me.readonly'), 'Combined permission request is incomplete');
  click('[data-action="google-sync"][data-service="calendar"]');
  await waitFor(() => read().events.some(e => e.remote?.service === 'calendar'));
  const ids = read().events.filter(e => e.remote).map(e => e.id);
  click('[data-action="google-sync"][data-service="calendar"]');
  await waitFor(() => !document.querySelector('[data-action="google-sync"][data-service="calendar"]').disabled);
  assert(JSON.stringify(read().events.filter(e => e.remote).map(e => e.id)) === JSON.stringify(ids), 'Repeated sync duplicated events');
  assert(document.querySelector('.all-day-event')?.textContent === 'School holiday', 'All-day event is not in its own row');
  results.push('Calendar account, source selection, timed/all-day import, and deduplication');
  assert(document.querySelector('[data-source="classroom"]'), 'Classroom did not connect with the same sign-in');
  click('[data-action="google-sync"][data-service="classroom"]');
  await waitFor(() => read().tasks.some(t => t.remote?.service === 'classroom'));
  const task = read().tasks.find(t => t.remote?.service === 'classroom');
  click('#editor [data-action="close"]'); click('[data-page="tasks"]');
  click(`[data-action="complete"][data-id="${task.id}"]`);
  click('.layout-shortcut'); click('[data-tab="connections"]'); click('[data-action="google-sync"][data-service="classroom"]');
  await waitFor(() => !document.querySelector('[data-action="google-sync"][data-service="classroom"]').disabled);
  assert(read().tasks.find(t => t.id === task.id).done, 'Refresh lost personal completion');
  assert(!localStorage.getItem('daylight-planner-v1').includes('TEST_ONLY_NOT_A_REAL_TOKEN'), 'OAuth token was persisted');
  results.push('Classroom assignments and deadlines, preserved personal completion, no persisted token');
  const beforeFailure = JSON.stringify(read().events); window.__googleFixture.status = 403;
  click('[data-action="google-sync"][data-service="calendar"]');
  await waitFor(() => document.querySelector('#editor').textContent.includes('Google denied access'));
  assert(JSON.stringify(read().events) === beforeFailure, 'Failed sync removed existing events');
  results.push('Failed sync leaves existing data intact and displays an actionable error');
  window.__googleFixture.status = 200; window.__googleFixture.deleted = true;
  click('[data-action="google-sync"][data-service="calendar"]');
  await waitFor(() => !read().events.some(e => e.remote?.service === 'calendar'));
  assert(read().events.some(e => !e.remote), 'Google refresh removed personal events');
  results.push('Google deletions remove imports without removing local plans');
  window.__googleFixture.accountId = 'another-account'; window.__googleFixture.email = 'another@example.test';
  click('[data-action="google-connect"]');
  await waitFor(() => document.querySelector('.google-account-card').textContent.includes('another@example.test') && !document.querySelector('[data-action="google-connect"]').disabled);
  assert(!read().tasks.some(t => t.remote?.account === 'fixture-account'), 'Account switch retained previous account imports');
  assert(read().tasks.some(t => !t.remote), 'Account switch removed personal tasks');
  results.push('Account switching replaces both connections and clears only previous account imports');
  click('[data-action="google-signout"]');
  assert(!document.querySelector('[data-source]'), 'Sign out did not disconnect both services');
  results.push('One sign-out disconnects Calendar and Classroom');
  return results;
})()
